# ═══════════════════════════════════════════════════════════
#  التقارير
# ═══════════════════════════════════════════════════════════

def تقرير(عنوان, صفوف, أعرض=None):
    """إنشاء تقرير منسق"""
    سطور = []

    # العنوان
    سطور.append("=" * 60)
    سطور.append(f"  {عنوان}")
    سطور.append("=" * 60)
    سطور.append("")

    # الأعمدة
    if not صفوف:
        سطور.append("  (لا توجد بيانات)")
        return "\n".join(سطور)

    أعمدة = أعرض if أعرض else list(صفوف[0].keys())

    # رأس الجدول
    رأس = " | ".join(f"{ع:^15}" for ع in أعمدة)
    سطور.append(رأس)
    سطور.append("-" * len(رأس))

    # الصفوف
    for ص in صفوف:
        قيم = " | ".join(f"{str(ص.get(ع, '')):^15}" for ع in أعمدة)
        سطور.append(قيم)

    سطور.append("-" * len(رأس))
    سطور.append(f"  الإجمالي: {len(صفوف)} سجل")
    سطور.append("=" * 60)

    return "\n".join(سطور)


def عرض_تقرير(عنوان, صفوف, أعرض=None):
    """طباعة تقرير"""
    print(تقرير(عنوان, صفوف, أعرض))


# ═══════════════════════════════════════════════════════════
#  المحاسبة
# ═══════════════════════════════════════════════════════════

def مجموع_مالي(صفوف, عمود):
    """TOTAL — المجموع المالي"""
    return sum(ص.get(عمود, 0) for ص in صفوف)


def متوسط_مالي(صفوف, عمود):
    """المتوسط المالي"""
    if not صفوف:
        return 0
    return مجموع_مالي(صفوف, عمود) / len(صفوف)


def أقصى_مالي(صفوف, عمود):
    """أقصى قيمة"""
    if not صفوف:
        return 0
    return max(ص.get(عمود, 0) for ص in صفوف)


def أدنى_مالي(صفوف, عمود):
    """أدنى قيمة"""
    if not صفوف:
        return 0
    return min(ص.get(عمود, 0) for ص in صفوف)


def ضريبة(مبلغ, نسبة=0.15):
    """حساب الضريبة"""
    return مبلغ * نسبة


def إجمالي_مع_ضريبة(مبلغ, نسبة=0.15):
    """الإجمالي مع الضريبة"""
    return مبلغ + ضريبة(مبلغ, نسبة)


def خصم(مبلغ, نسبة):
    """حساب الخصم"""
    return مبلغ * (1 - نسبة)


def ربح(تكلفة, سعر_بيع):
    """حساب الربح"""
    return سعر_بيع - تكلفة


def نسبة_ربح(تكلفة, سعر_بيع):
    """نسبة الربح"""
    if تكلفة == 0:
        return 0
    return ((سعر_بيع - تكلفة) / تكلفة) * 100


# ═══════════════════════════════════════════════════════════
#  تنسيق
# ═══════════════════════════════════════════════════════════

def ريال(مبلغ, عشريات=2):
    """تنسيق مبلغ بالريال"""
    return f"{مبلغ:,.{عشريات}f} ر.س"


def دولار(مبلغ, عشريات=2):
    """تنسيق مبلغ بالدولار"""
    return f"${مبلغ:,.{عشريات}f}"


def نسبة(قيمة, عشريات=1):
    """تنسيق النسبة"""
    return f"{قيمة:.{عشريات}f}%"


def رصيد(مدين, دائن):
    """حساب الرصيد"""
    return مدين - دائن


# ═══════════════════════════════════════════════════════════
#  المعالجة
# ═══════════════════════════════════════════════════════════

def رتّب_حسب(صفوف, عمود, عكسي=False):
    """ترتيب حسب عمود"""
    return sorted(صفوف, key=lambda ص: ص.get(عمود, 0), reverse=عكسي)


def صفّي(صفوف, شرط):
    """تصفية الصفوف"""
    return [ص for ص in صفوف if شرط(ص)]


def جمّع_حسب(صفوف, عمود_مجموعة, عمود_قيمة):
    """تجميع حسب عمود"""
    نتيجة = {}
    for ص in صفوف:
        مفتاح = ص.get(عمود_مجموعة, "")
        قيمة = ص.get(عمود_قيمة, 0)
        if مفتاح not in نتيجة:
            نتيجة[مفتاح] = 0
        نتيجة[مفتاح] += قيمة
    return نتيجة


