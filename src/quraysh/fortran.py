import math


# ═══════════════════════════════════════════════════════════
#  الدوال المثلثية
# ═══════════════════════════════════════════════════════════

def جيب(زاوية):
    """sin — الجيب"""
    return math.sin(زاوية)


def جيب_تمام(زاوية):
    """cos — جيب التمام"""
    return math.cos(زاوية)


def ظل(زاوية):
    """tan — الظل"""
    return math.tan(زاوية)


def ظل_تمام(زاوية):
    """cot — ظل التمام"""
    return 1 / math.tan(زاوية)


def قاطع(زاوية):
    """sec — القاطع"""
    return 1 / math.cos(زاوية)


def قاطع_تمام(زاوية):
    """csc — قاطع التمام"""
    return 1 / math.sin(زاوية)


# ═══════════════════════════════════════════════════════════
#  الدوال العكسية
# ═══════════════════════════════════════════════════════════

def جيب_عكسي(قيمة):
    """arcsin — الجيب العكسي"""
    return math.asin(قيمة)


def جيب_تمام_عكسي(قيمة):
    """arccos — جيب التمام العكسي"""
    return math.acos(قيمة)


def ظل_عكسي(قيمة):
    """arctan — الظل العكسي"""
    return math.atan(قيمة)


# ═══════════════════════════════════════════════════════════
#  الدوال اللوغاريتمية
# ═══════════════════════════════════════════════════════════

def لوغاريتم(عدد, أساس=10):
    """log — اللوغاريتم"""
    return math.log(عدد, أساس)


def لوغاريتم_طبيعي(عدد):
    """ln — اللوغاريتم الطبيعي"""
    return math.log(عدد)


def أس(عدد):
    """exp — الأس"""
    return math.exp(عدد)


# ═══════════════════════════════════════════════════════════
#  الدوال الأسية والجذرية
# ═══════════════════════════════════════════════════════════

def جذر_ن(عدد, ن=2):
    """nth root — الجذر النوني"""
    return عدد ** (1 / ن)


def قوة_ن(أساس, أس):
    """power — القوة"""
    return أساس ** أس


# ═══════════════════════════════════════════════════════════
#  الدوال الهندسية
# ═══════════════════════════════════════════════════════════

def مساحة_مثلث(قاعدة, ارتفاع):
    """مساحة المثلث"""
    return 0.5 * قاعدة * ارتفاع


def مساحة_دائرة(نصف_قطر):
    """مساحة الدائرة"""
    return math.pi * نصف_قطر ** 2


def محيط_دائرة(نصف_قطر):
    """محيط الدائرة"""
    return 2 * math.pi * نصف_قطر


def مساحة_مستطيل(طول, عرض):
    """مساحة المستطيل"""
    return طول * عرض


def مساحة_مربع(ضلع):
    """مساحة المربع"""
    return ضلع ** 2


def حجم_كرة(نصف_قطر):
    """حجم الكرة"""
    return (4 / 3) * math.pi * نصف_قطر ** 3


def حجم_مكعب(ضلع):
    """حجم المكعب"""
    return ضلع ** 3


# ═══════════════════════════════════════════════════════════
#  الدوال الإحصائية
# ═══════════════════════════════════════════════════════════

def متوسط(*أعداد):
    """mean — المتوسط"""
    if not أعداد:
        return 0
    return sum(أعداد) / len(أعداد)


def وسيط(*أعداد):
    """median — الوسيط"""
    if not أعداد:
        return 0
    قائمة = sorted(أعداد)
    n = len(قائمة)
    if n % 2 == 0:
        return (قائمة[n // 2 - 1] + قائمة[n // 2]) / 2
    return قائمة[n // 2]


def انحراف(أعداد):
    """std — الانحراف المعياري"""
    if not أعداد:
        return 0
    م = متوسط(*أعداد)
    تباين = sum((x - م) ** 2 for x in أعداد) / len(أعداد)
    return math.sqrt(تباين)


def مجموع(*أعداد):
    """sum — المجموع"""
    return sum(أعداد)


def أكبر(*أعداد):
    """max — الأكبر"""
    return max(أعداد) if أعداد else 0


def أصغر(*أعداد):
    """min — الأصغر"""
    return min(أعداد) if أعداد else 0


