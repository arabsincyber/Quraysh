    عقد = parse_contract(كود)
    print(عقد.ملخص())
    print()

    print("اختبار الانتهاك:")
    عقد2 = Contract()
    عقد2.يعلن([])

    try:
        عقد2.يستخدم("شبكة")
    except SecurityViolation as e:
        print(f"  ✓ تم كشف الانتهاك: {e}")

    print()
    print("قالب جاهز:")
    print(generate_contract_template(
        مطور="محمد",
        وصف="برنامج ترحيبي",
        أذونات=[]
    ))
