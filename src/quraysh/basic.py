"""
BASIC — Beginner's All-purpose Symbolic Instruction Code
=========================================================

مكتبة BASIC العربية — لسان قريش.

مبنية على مبادئ BASIC (1964) — لغة التعليم الشهيرة.

الأوامر:
- اقرأ (INPUT) — قراءة مدخلات
- كرر (FOR) — حلقة محسوبة
- بينما (WHILE) — حلقة شرطية
- اذهب (GOTO) — قفزة
- استدع (GOSUB) — استدعاء دالة
- أرجع (RETURN) — إرجاع
"""


# ═══════════════════════════════════════════════════════════
#  المدخلات
# ═══════════════════════════════════════════════════════════

def اقرأ(رسالة=""):
    """INPUT — قراءة مدخلات المستخدم"""
    return input(رسالة)


def اقرأ_رقم(رسالة=""):
    """قراءة رقم"""
    while True:
        try:
            return float(input(رسالة))
        except ValueError:
            print("⚠️  من فضلك أدخل رقماً")


def اقرأ_عدد(رسالة=""):
    """قراءة عدد صحيح"""
    while True:
        try:
            return int(input(رسالة))
        except ValueError:
            print("⚠️  من فضلك أدخل عدداً صحيحاً")


# ═══════════════════════════════════════════════════════════
#  الحلقات (تقليدية — للاستخدام الداخلي)
# ═══════════════════════════════════════════════════════════

def كرر_من_إلى(بداية, نهاية):
    """FOR — من...إلى"""
    return list(range(بداية, نهاية + 1))


def كرر_خطوة(بداية, نهاية, خطوة):
    """FOR...STEP — من...إلى...خطوة"""
    return list(range(بداية, نهاية + 1, خطوة))


def بينما_عد(شرط_دالة, جسم_دالة, حد_أقصى=10000):
    """WHILE — بينما"""
    عداد = 0
    while شرط_دالة() and عداد < حد_أقصى:
        جسم_دالة()
        عداد += 1


# ═══════════════════════════════════════════════════════════
#  أدوات BASIC
# ═══════════════════════════════════════════════════════════

def طول_نص(نص):
    """LEN — طول النص"""
    return len(نص)


def جزء_نص(نص, بداية, طول):
    """MID$ — جزء من النص"""
    return نص[بداية:بداية + طول]


def يسار(نص, عدد):
    """LEFT$ — أول عدد أحرف"""
    return نص[:عدد]


def يمين(نص, عدد):
    """RIGHT$ — آخر عدد أحرف"""
    return نص[-عدد:] if عدد > 0 else ""


def رمز(حرف):
    """ASC — رمز الحرف"""
    return ord(حرف) if حرف else 0


def حرف(رمز):
    """CHR$ — الحرف من الرمز"""
    return chr(int(رمز))


def عشوائي(من=0, إلى=1):
    """RND — رقم عشوائي"""
    import random
    if isinstance(من, int) and isinstance(إلى, int):
        return random.randint(من, إلى)
    return random.random()


def تقريب_عدد(عدد, خانات=0):
    """ROUND — تقريب"""
    return round(عدد, خانات)


def صحيح(عدد):
    """INT — الجزء الصحيح"""
    return int(عدد)


def مطلق_عدد(عدد):
    """ABS — القيمة المطلقة"""
    return abs(عدد)


def إشارة(عدد):
    """SGN — الإشارة"""
    return (عدد > 0) - (عدد < 0)


