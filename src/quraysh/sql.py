    for ص in مرتّب:
        print(f"  {ص['اسم']} — {ص['عمر']}")
    print()

    # تحديث
    print(قاعدة.حدّث("طلاب", حيث_يساوي("مدينة", "الرياض"), {"مدينة": "الرياض الملقا"}))
    print()

    # عرض محدّث
    print(قاعدة.اعرض("طلاب"))
    print()

    # حذف
    print(قاعدة.احذف("طلاب", حيث_يساوي("اسم", "صالح")))
    print()

    # عرض نهائي
    print(قاعدة.اعرض("طلاب"))
    print()
