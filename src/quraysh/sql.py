"""
SQL — Structured Query Language
================================

مكتبة SQL العربية — لسان قريش.

مبنية على مبادئ SQL (1974) — لغة قواعد البيانات.

المزايا:
- جداول في الذاكرة
- استعلامات
- إدراج، تحديث، حذف
- ترتيب وتصفية
"""


# ═══════════════════════════════════════════════════════════
#  قاعدة البيانات
# ═══════════════════════════════════════════════════════════

class قاعدة_بيانات:
    """قاعدة بيانات في الذاكرة"""

    def __init__(self):
        self.جداول = {}

    def أنشئ_جدول(self, اسم, أعمدة):
        """CREATE TABLE — إنشاء جدول"""
        self.جداول[اسم] = {
            'أعمدة': أعمدة,
            'صفوف': []
        }
        return f"✓ تم إنشاء الجدول '{اسم}' بـ {len(أعمدة)} أعمدة"

    def أدرج(self, جدول, **قيم):
        """INSERT — إدراج صف"""
        if جدول not in self.جداول:
            raise ValueError(f"الجدول غير موجود: {جدول}")
        self.جداول[جدول]['صفوف'].append(قيم)
        return f"✓ تم إدراج صف في '{جدول}'"

    def اختر(self, جدول, حيث=None):
        """SELECT — اختيار صفوف"""
        if جدول not in self.جداول:
            raise ValueError(f"الجدول غير موجود: {جدول}")

        صفوف = self.جداول[جدول]['صفوف']

        if حيث:
            صفوف = [ص for ص in صفوف if حيث(ص)]

        return صفوف

    def حدّث(self, جدول, حيث, تحديث):
        """UPDATE — تحديث صفوف"""
        if جدول not in self.جداول:
            raise ValueError(f"الجدول غير موجود: {جدول}")

        عداد = 0
        for ص in self.جداول[جدول]['صفوف']:
            if حيث(ص):
                ص.update(تحديث)
                عداد += 1

        return f"✓ تم تحديث {عداد} صف"

    def احذف(self, جدول, حيث):
        """DELETE — حذف صفوف"""
        if جدول not in self.جداول:
            raise ValueError(f"الجدول غير موجود: {جدول}")

        قبل = len(self.جداول[جدول]['صفوف'])
        self.جداول[جدول]['صفوف'] = [
            ص for ص in self.جداول[جدول]['صفوف'] if not حيث(ص)
        ]
        بعد = len(self.جداول[جدول]['صفوف'])

        return f"✓ تم حذف {قبل - بعد} صف"

    def اعرض(self, جدول):
        """عرض الجدول"""
        if جدول not in self.جداول:
            return f"الجدول غير موجود: {جدول}"

        أعمدة = self.جداول[جدول]['أعمدة']
        صفوف = self.جداول[جدول]['صفوف']

        if not صفوف:
            return f"الجدول '{جدول}' فارغ"

        سطور = [f"جدول: {جدول}"]
        سطور.append(" | ".join(أعمدة))
        سطور.append("-" * 40)

        for ص in صفوف:
            قيم = [str(ص.get(ع, "")) for ع in أعمدة]
            سطور.append(" | ".join(قيم))

        return "\n".join(سطور)


# ═══════════════════════════════════════════════════════════
#  دوال مساعدة
# ═══════════════════════════════════════════════════════════

def حيث_يساوي(عمود, قيمة):
    """شرط: عمود = قيمة"""
    return lambda ص: ص.get(عمود) == قيمة


def حيث_أكبر(عمود, قيمة):
    """شرط: عمود > قيمة"""
    return lambda ص: ص.get(عمود, 0) > قيمة


def حيث_أصغر(عمود, قيمة):
    """شرط: عمود < قيمة"""
    return lambda ص: ص.get(عمود, 0) < قيمة


def حيث_يحتوي(عمود, نص):
    """شرط: عمود يحتوي نص"""
    return lambda ص: نص in str(ص.get(عمود, ""))


def رتب_حسب(جدول, عمود, عكسي=False):
    """ORDER BY — ترتيب"""
    return sorted(جدول, key=lambda ص: ص.get(عمود, ""), reverse=عكسي)


def عدّ(صفوف):
    """COUNT — عدّ"""
    return len(صفوف)


