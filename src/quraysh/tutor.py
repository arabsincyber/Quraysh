_مساعد_عام = None


def _احصل_على_المساعد():
    global _مساعد_عام
    if _مساعد_عام is None:
        _مساعد_عام = مساعد_لسان_قريش()
    return _مساعد_عام


def _اسم_نصي(قيمة):
    """يحوّل أي قيمة إلى اسم نصي"""
    if callable(قيمة):
        # دالة — نأخذ اسمها
        return getattr(قيمة, "__name__", str(قيمة))
    return str(قيمة)


def اشرح(اسم_دالة):
    """شرح دالة"""
    اسم = _اسم_نصي(اسم_دالة)
    نتيجة = _احصل_على_المساعد().اشرح_دالة(اسم)
    return نتيجة or f"❌ الدالة غير معروفة: {اسم}"


def اقترح_بديل(اسم_دالة):
    """اقتراح دالة قريبة"""
    اسم = _اسم_نصي(اسم_دالة)
    نتيجة = _احصل_على_المساعد().صحّح_دالة(اسم)
    return نتيجة or f"✅ الاسم صحيح: {اسم}"


def راجع(كود):
    """مراجعة كود كامل"""
    if not isinstance(كود, str):
        كود = str(كود)
    return _احصل_على_المساعد().اكتب_تقرير(كود)


