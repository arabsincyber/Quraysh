class مساعد_لسان_قريش:
    """مساعد ذكي — يشرح، يصحّح، ويقترح"""

    def __init__(self):
        self.بيغرام = _احصل_على_النموذج()
        self.سجل_الاقتراحات = []

    # ─────── تصحيح الدوال ───────

    def ابحث_عن_دالة(self, اسم, حد=0.7):
        """يبحث عن أقرب دالة للاسم المُدخل"""
        if اسم in قاموس_الدوال:
            return اسم, 1.0
        أفضل = None
        أفضل_نسبة = 0.0
        for دالة in قاموس_الدوال:
            نسبة = SequenceMatcher(None, اسم, دالة).ratio()
            if نسبة > أفضل_نسبة:
                أفضل_نسبة = نسبة
                أفضل = دالة
        return (أفضل, أفضل_نسبة) if أفضل_نسبة >= حد else (None, 0.0)

    def صحّح_دالة(self, اسم):
        """يقترح دالة قريبة"""
        بديل, نسبة = self.ابحث_عن_دالة(اسم)
        if بديل:
            return {
                "الأصل": اسم,
                "البديل": بديل,
                "الثقة": round(نسبة * 100),
                "الشرح": قاموس_الدوال[بديل][0],
                "المثال": قاموس_الدوال[بديل][1],
            }
        return None

    # ─────── شرح ───────

    def اشرح_دالة(self, اسم):
        """شرح مبسط للدالة"""
        if اسم in قاموس_الدوال:
            وصف, مثال = قاموس_الدوال[اسم]
            return {
                "الدالة": اسم,
                "الوصف": وصف,
                "المثال": مثال,
            }
        return None

    # ─────── اقتراح أمثلة ───────

    def اقترح_مثال(self, موضوع):
        """يقترح مثالاً بناءً على موضوع"""
        مطابقة = {
            "تشفير": ["بصمة_نص", "ترميز_base64", "تشفير_xor"],
            "شبكة": ["استعلم_dns", "افتح_منفذ", "ip_الحالي"],
            "قاعدة": ["أنشئ_جدول", "أدرج", "اعرض"],
            "ملف": ["اقرأ", "اكتب", "موجود"],
            "رياضيات": ["جذر_ن", "مساحة_مثلث", "متوسط"],
            "نص": ["طول_نص", "يسار", "يمين"],
        }
        دوال_مقترحة = مطابقة.get(موضوع, [])
        return [
            {"الدالة": د, "الشرح": قاموس_الدوال[د][0], "المثال": قاموس_الدوال[د][1]}
            for د in دوال_مقترحة if د in قاموس_الدوال
        ]

    # ─────── تحليل خطأ ───────

    def حلّل_خطأ(self, رسالة_الخطأ, كود=""):
        """يحلّل رسالة خطأ ويقترح حلولاً"""
        نتائج = {"الخطأ": رسالة_الخطأ, "اقتراحات": []}

        # 1. اسم دالة غير معروف
        m = re.search(r"NameError|غير معروف|undefined", رسالة_الخطأ, re.IGNORECASE)
        if m and كود:
            كلمات = re.findall(r"[\u0600-\u06FF_]+", كود)
            for كلمة in كلمات:
                اقتراح = self.صحّح_دالة(كلمة)
                if اقتراح:
                    نتائج["اقتراحات"].append({
                        "نوع": "دالة",
                        **اقتراح,
                    })

        # 2. خطأ صياغة
        if "SyntaxError" in رسالة_الخطأ or "قوس" in رسالة_الخطأ:
            نتائج["اقتراحات"].append({
                "نوع": "صياغة",
                "رسالة": "تحقق من الأقواس المتوازنة ()",
            })

        # 3. خطأ نوع
        if "TypeError" in رسالة_الخطأ:
            نتائج["اقتراحات"].append({
                "نوع": "نوع",
                "رسالة": "تأكد من أنواع المعاملات (نص/رقم)",
            })

        return نتائج

    # ─────── تصحيح كود كامل ───────

    def راجع_كود(self, كود):
        """فحص شامل لكود المستخدم"""
        نتائج = {
            "تصحيحات": [],
            "توقعات": [],
            "إحصاءات": {},
        }

        # 1. ابحث عن كلمات عربية في الكود
        كلمات = re.findall(r"[\u0600-\u06FF_]+", كود)

        # 2. لكل كلمة — هل هي دالة معروفة؟
        for كلمة in set(كلمات):
            if كلمة in قاموس_الدوال:
                continue
            اقتراح = self.صحّح_دالة(كلمة)
            if اقتراح and اقتراح["الثقة"] >= 75:
                نتائج["تصحيحات"].append(اقتراح)

        # 3. توقعات الكلمة التالية
        مطابقة = re.findall(r"\(([\u0600-\u06FF_]+)", كود)
        if مطابقة:
            آخر_دالة = مطابقة[-1]
            توقعات = self.بيغرام.توقّع(آخر_دالة, 3)
            نتائج["توقعات"] = [
                {"الكلمة": ك, "الثقة": ع}
                for ك, ع in توقعات
            ]

        # 4. إحصاءات
        نتائج["إحصاءات"] = {
            "الأسطر": len(كود.split("\n")),
            "الكلمات": len(كلمات),
            "الأقواس": كود.count("(") + كود.count(")"),
            "الأقواس_متوازنة": كود.count("(") == كود.count(")"),
        }

        return نتائج

    # ─────── تقرير للمستخدم ───────

    def اكتب_تقرير(self, كود):
        """يولّد تقرير مقروء بالعربي"""
        نتائج = self.راجع_كود(كود)
        سطور = []
        سطور.append("═" * 50)
        سطور.append("  🎓 تقرير المساعد الذكي")
        سطور.append("═" * 50)

        # الإحصاءات
        إ = نتائج["إحصاءات"]
        سطور.append(f"\n📊 الأسطر: {إ['الأسطر']} • الكلمات: {إ['الكلمات']}")
        حالة = "✅" if إ["الأقواس_متوازنة"] else "❌"
        سطور.append(f"   الأقواس: {إ['الأقواس']} {حالة}")

        # التصحيحات
        if نتائج["تصحيحات"]:
            سطور.append("\n🔧 اقتراحات التصحيح:")
            for ت in نتائج["تصحيحات"][:5]:
                سطور.append(f"   '{ت['الأصل']}' → '{ت['البديل']}'  ({ت['الثقة']}%)")
                سطور.append(f"      {ت['الشرح']}")
        else:
            سطور.append("\n✅ لا اقتراحات تصحيح")

        # التوقعات
        if نتائج["توقعات"]:
            سطور.append("\n🔮 الكلمة التالية:")
            for ت in نتائج["توقعات"][:3]:
                سطور.append(f"   {ت['الكلمة']} ({ت['الثقة']})")

        سطور.append("\n" + "═" * 50)
        return "\n".join(سطور)


