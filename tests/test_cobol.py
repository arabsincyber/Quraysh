"""اختبارات مكتبة COBOL — cobol.py"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

import pytest
from quraysh.cobol import (
    ضريبة, إجمالي_مع_ضريبة, خصم, ربح, نسبة_ربح,
    ريال, دولار, نسبة, رصيد,
    رتّب_حسب, صفّي, جمّع_حسب,
    مجموع_مالي, متوسط_مالي, أقصى_مالي, أدنى_مالي,
    دوال_COBOL,
)


@pytest.fixture
def صفوف():
    return [
        {"اسم": "محمد", "مبلغ": 1000},
        {"اسم": "صالح", "مبلغ": 3000},
        {"اسم": "عبدالله", "مبلغ": 2000},
    ]


def test_عدد_الدوال():
    assert len(دوال_COBOL) == 18

def test_ضريبة_افتراضي():
    assert ضريبة(10000) == 1500.0

def test_ضريبة_مخصص():
    assert ضريبة(1000, 0.05) == 50

def test_إجمالي_مع_ضريبة():
    assert إجمالي_مع_ضريبة(1000, 0.1) == 1100

def test_خصم():
    assert خصم(1000, 0.1) == 900.0

def test_ربح():
    assert ربح(2500, 3500) == 1000

def test_ربح_خسارة():
    assert ربح(3500, 2500) == -1000

def test_نسبة_ربح():
    assert نسبة_ربح(100, 150) == 50.0

def test_ريال():
    نتيجة = ريال(3500)
    assert "3,500" in نتيجة or "3500" in نتيجة

def test_دولار():
    نتيجة = دولار(1500)
    assert "1,500" in نتيجة or "1500" in نتيجة or "$" in نتيجة

def test_نسبة():
    نتيجة = نسبة(25)
    assert "25" in نتيجة

def test_رصيد():
    نتيجة = رصيد(1000, 500)
    assert نتيجة == 500 or "500" in str(نتيجة)

def test_رتّب_حسب(صفوف):
    نتيجة = رتّب_حسب(صفوف, "مبلغ")
    assert نتيجة[0]["مبلغ"] == 1000

def test_رتّب_عكسي(صفوف):
    نتيجة = رتّب_حسب(صفوف, "مبلغ", عكسي=True)
    assert نتيجة[0]["مبلغ"] == 3000

def test_صفّي(صفوف):
    نتيجة = صفّي(صفوف, lambda ص: ص["مبلغ"] > 1500)
    assert len(نتيجة) == 2

def test_مجموع_مالي(صفوف):
    assert مجموع_مالي(صفوف, "مبلغ") == 6000

def test_متوسط_مالي(صفوف):
    assert متوسط_مالي(صفوف, "مبلغ") == 2000.0

def test_أقصى_مالي(صفوف):
    assert أقصى_مالي(صفوف, "مبلغ") == 3000

def test_أدنى_مالي(صفوف):
    assert أدنى_مالي(صفوف, "مبلغ") == 1000

def test_جمّع_حسب():
    صفوف = [
        {"قسم": "أ", "مبلغ": 100},
        {"قسم": "ب", "مبلغ": 200},
        {"قسم": "أ", "مبلغ": 150},
    ]
    نتيجة = جمّع_حسب(صفوف, "قسم", "مبلغ")
    assert نتيجة.get("أ") == 250
    assert نتيجة.get("ب") == 200
