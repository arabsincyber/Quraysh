"""اختبارات مكتبة SQL — sql.py"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

import pytest
from quraysh.sql import (
    قاعدة_بيانات, حيث_يساوي, حيث_أكبر, حيث_أصغر,
    حيث_يحتوي, رتب_حسب, عدّ, دوال_القاعدة,
)


@pytest.fixture
def قاعدة():
    q = قاعدة_بيانات()
    q.أنشئ_جدول("طلاب", ["اسم", "عمر", "مدينة"])
    q.أدرج("طلاب", اسم="محمد", عمر=25, مدينة="الرياض")
    q.أدرج("طلاب", اسم="صالح", عمر=30, مدينة="جدة")
    q.أدرج("طلاب", اسم="عبدالله", عمر=28, مدينة="الدمام")
    return q


def test_إنشاء_جدول(قاعدة):
    assert "طلاب" in قاعدة.جداول

def test_إدراج_صف(قاعدة):
    assert len(قاعدة.جداول["طلاب"]["صفوف"]) == 3

def test_اختيار_الكل(قاعدة):
    صفوف = قاعدة.اختر("طلاب")
    assert len(صفوف) == 3

def test_اختيار_حيث_يساوي(قاعدة):
    صفوف = قاعدة.اختر("طلاب", حيث_يساوي("مدينة", "جدة"))
    assert len(صفوف) == 1
    assert صفوف[0]["اسم"] == "صالح"

def test_اختيار_حيث_أكبر(قاعدة):
    صفوف = قاعدة.اختر("طلاب", حيث_أكبر("عمر", 26))
    assert len(صفوف) == 2

def test_اختيار_حيث_أصغر(قاعدة):
    صفوف = قاعدة.اختر("طلاب", حيث_أصغر("عمر", 28))
    assert len(صفوف) == 1

def test_اختيار_حيث_يحتوي(قاعدة):
    صفوف = قاعدة.اختر("طلاب", حيث_يحتوي("مدينة", "ال"))
    assert len(صفوف) == 2  # الرياض، الدمام

def test_رتب_حسب(قاعدة):
    صفوف = قاعدة.اختر("طلاب")
    مرتّب = رتب_حسب(صفوف, "عمر")
    assert مرتّب[0]["عمر"] == 25
    assert مرتّب[-1]["عمر"] == 30

def test_رتب_حسب_عكسي(قاعدة):
    صفوف = قاعدة.اختر("طلاب")
    مرتّب = رتب_حسب(صفوف, "عمر", عكسي=True)
    assert مرتّب[0]["عمر"] == 30

def test_عدّ(قاعدة):
    صفوف = قاعدة.اختر("طلاب")
    assert عدّ(صفوف) == 3

def test_تحديث(قاعدة):
    نتيجة = قاعدة.حدّث("طلاب", حيث_يساوي("اسم", "محمد"), {"مدينة": "جدة"})
    assert "1" in نتيجة
    صفوف = قاعدة.اختر("طلاب", حيث_يساوي("اسم", "محمد"))
    assert صفوف[0]["مدينة"] == "جدة"

def test_حذف(قاعدة):
    نتيجة = قاعدة.احذف("طلاب", حيث_يساوي("اسم", "صالح"))
    assert "1" in نتيجة
    assert len(قاعدة.اختر("طلاب")) == 2

def test_عرض_جدول(قاعدة):
    نتيجة = قاعدة.اعرض("طلاب")
    assert "جدول: طلاب" in نتيجة
    assert "محمد" in نتيجة

def test_جدول_غير_موجود():
    q = قاعدة_بيانات()
    with pytest.raises(ValueError):
        q.أدرج("غير_موجود", اسم="x")

def test_عدد_دوال_القاعدة():
    assert len(دوال_القاعدة) == 10
