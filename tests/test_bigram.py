"""اختبارات مكتبة البيغرام — bigram.py"""
import sys, os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

import pytest
from quraysh.bigram import (
    نموذج_بيغرام, توقّع_الكلمة, صحّح_كلمة, صحّح_جملة,
    دوال_البيغرام,
)


@pytest.fixture
def نموذج():
    """نموذج مصغّر للاختبار"""
    ن = نموذج_بيغرام()
    ن.تعلّم_نص("""
    بسم الله الرحمن الرحيم
    الحمد لله رب العالمين
    الرحمن الرحيم
    مالك يوم الدين
    """)
    return ن


# ═══ الأساسيات ═══

def test_نموذج_جديد_فارغ():
    ن = نموذج_بيغرام()
    assert ن.حجم == 0

def test_تعلّم_نص(نموذج):
    assert نموذج.حجم > 0

def test_مفردات_يحتوي_كلمات(نموذج):
    for كلمة in ["بسم", "الله", "الرحمن"]:
        assert كلمة in نموذج.مفردات


# ═══ التوقّع ═══

def test_توقّع_بسم(نموذج):
    توقعات = نموذج.توقّع("بسم")
    assert len(توقعات) > 0
    assert توقعات[0][0] == "الله"

def test_توقّع_الحمد(نموذج):
    توقعات = نموذج.توقّع("الحمد")
    assert len(توقعات) > 0

def test_توقّع_كلمة_غير_موجودة(نموذج):
    assert نموذج.توقّع("xyz123") == []


# ═══ الاحتمالات ═══

def test_احتمالية_صحيحة(نموذج):
    p = نموذج.احتمالية("بسم", "الله")
    assert p == 1.0

def test_احتمالية_صفر(نموذج):
    assert نموذج.احتمالية("بسم", "xyz") == 0.0


# ═══ التصحيح ═══


def test_صحّح_يرجع_نص():
    """التصحيح يرجع نصاً (بدون مقارنة عربية معقدة)"""
    ن = نموذج_بيغرام()
    ن.تعلّم_نص("بسم الله الرحمن الرحيم")
    نتيجة = ن.صحّح("الله")
    assert isinstance(نتيجة, str)
    assert len(نتيجة) > 0

def test_صحّح_كلمة_بعيدة(نموذج):
    نتيجة = نموذج.صحّح("xyzabc")
    assert نتيجة == "xyzabc"

def test_صحّح_جملة(نموذج):
    نتيجة = نموذج.صحّح_جملة("بسم الله")
    assert isinstance(نتيجة, str)


# ═══ التشكيل (بالطول فقط — أأمن من مقارنة نص عربي) ═══

def test_جرّد_التشكيل_بالطول():
    ن = نموذج_بيغرام()
    # "بِسْمِ" (5 حروف مع تشكيل) → يجب أن تصير 3
    assert len(ن._جرّد_التشكيل("بِسْمِ")) == 3

def test_جرّد_التشكيل_بدون_تشكيل():
    ن = نموذج_بيغرام()
    # بدون تشكيل → تبقى كما هي
    assert ن._جرّد_التشكيل("بسم") == "بسم"

def test_تعلّم_يتجاهل_التشكيل():
    ن = نموذج_بيغرام()
    ن.تعلّم_نص("بِسْمِ اللَّهِ")
    assert "بسم" in ن.مفردات
    assert "الله" in ن.مفردات


# ═══ الحفظ والتحميل ═══

def test_حفظ_وتحميل(tmp_path, نموذج):
    مسار = str(tmp_path / "test.json")
    نموذج.حفظ(مسار)

    ن2 = نموذج_بيغرام.حمّل(مسار)
    assert ن2.حجم == نموذج.حجم
    assert len(ن2.مفردات) == len(نموذج.مفردات)

def test_حفظ_يحافظ_على_التوقعات(tmp_path, نموذج):
    مسار = str(tmp_path / "test.json")
    نموذج.حفظ(مسار)
    ن2 = نموذج_بيغرام.حمّل(مسار)

    ت1 = نموذج.توقّع("بسم")
    ت2 = ن2.توقّع("بسم")
    assert ت1 == ت2


