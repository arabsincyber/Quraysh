# ═══ قاموس الدوال ═══

def test_قاموس_ليس_فارغ():
    assert len(قاموس_الدوال) > 50

def test_قاموس_يحتوي_أساسيات():
    for دالة in ["اطبع", "تعريف", "لامدا", "إذا"]:
        assert دالة in قاموس_الدوال

def test_قاموس_يحتوي_crypto():
    for دالة in ["بصمة_نص", "ترميز_base64", "تشفير_xor"]:
        assert دالة in قاموس_الدوال

def test_قاموس_يحتوي_sql():
    for دالة in ["أنشئ_جدول", "أدرج", "اعرض"]:
        assert دالة in قاموس_الدوال


# ═══ الشرح ═══

def test_اشرح_دالة_موجودة(مساعد):
    نتيجة = مساعد.اشرح_دالة("بصمة_نص")
    assert نتيجة is not None
    assert "الدالة" in نتيجة
    assert نتيجة["الدالة"] == "بصمة_نص"

def test_اشرح_دالة_غير_موجودة(مساعد):
    نتيجة = مساعد.اشرح_دالة("دالة_وهمية")
    assert نتيجة is None

def test_اشرح_عبر_دالة_عامة():
    نتيجة = اشرح("بصمة_نص")
    assert "بصمة_نص" in str(نتيجة) or "SHA" in str(نتيجة)


# ═══ التصحيح ═══

def test_صحّح_دالة_بخطأ_إملائي(مساعد):
    نتيجة = مساعد.صحّح_دالة("بصمه_نص")
    assert نتيجة is not None
    assert نتيجة["البديل"] == "بصمة_نص"
    assert نتيجة["الثقة"] > 70

def test_صحّح_دالة_بعيدة(مساعد):
    نتيجة = مساعد.صحّح_دالة("xyz")
    assert نتيجة is None

def test_اقترح_بديل_عبر_دالة_عامة():
    نتيجة = اقترح_بديل("بصمه_نص")
    assert "بصمة_نص" in str(نتيجة)


# ═══ اقتراح أمثلة ═══

def test_اقترح_مثال_تشفير(مساعد):
    نتيجة = مساعد.اقترح_مثال("تشفير")
    assert len(نتيجة) > 0
    أسماء = [م["الدالة"] for م in نتيجة]
    assert "بصمة_نص" in أسماء

def test_اقترح_مثال_شبكة(مساعد):
    نتيجة = مساعد.اقترح_مثال("شبكة")
    assert len(نتيجة) > 0

def test_اقترح_مثال_موضوع_غير_معروف(مساعد):
    نتيجة = مساعد.اقترح_مثال("موضوع_وهمي")
    assert نتيجة == []


# ═══ تحليل الأخطاء ═══

def test_حلّل_خطأ_name_error(مساعد):
    نتيجة = مساعد.حلّل_خطأ("NameError: بصمه_نص غير معروف", '(بصمه_نص "قريش")')
    assert "الخطأ" in نتيجة
    assert isinstance(نتيجة["اقتراحات"], list)

def test_حلّل_خطأ_syntax(مساعد):
    نتيجة = مساعد.حلّل_خطأ("SyntaxError: قوس مغلق غير متوقع", '(اطبع "مرحبا"')
    assert len(نتيجة["اقتراحات"]) > 0


# ═══ تحليل الكود ═══

def test_راجع_كود_بسيط(مساعد):
    نتيجة = مساعد.راجع_كود('(اطبع "مرحبا")')
    assert "إحصاءات" in نتيجة
    assert نتيجة["إحصاءات"]["الأقواس_متوازنة"] is True

def test_راجع_كود_غير_متوازن(مساعد):
    نتيجة = مساعد.راجع_كود('(اطبع "مرحبا"')
    assert نتيجة["إحصاءات"]["الأقواس_متوازنة"] is False

def test_راجع_كود_بخطأ_إملائي(مساعد):
    نتيجة = مساعد.راجع_كود('(بصمه_نص "قريش")')
    assert len(نتيجة["تصحيحات"]) > 0
    assert نتيجة["تصحيحات"][0]["البديل"] == "بصمة_نص"

def test_راجع_كود_سليم(مساعد):
    نتيجة = مساعد.راجع_كود('(بصمة_نص "قريش")')
    assert len(نتيجة["تصحيحات"]) == 0


